#!/bin/bash

# ============================================================================
# 批量运行所有消融实验
# 依次运行实验 (a), (b), (c)
# ============================================================================

set -e  # 遇到错误时退出

echo "========================================================================"
echo "批量运行所有消融实验"
echo "========================================================================"
echo ""

# 共享参数（可以根据需要修改）
COMMON_ARGS="--epochs 100 --finetune_epoch 25 --batch_size 32 --early_stopping_patience 10"

# 如果提供了额外参数，追加到共享参数
if [ $# -gt 0 ]; then
    echo "使用额外参数: $@"
    COMMON_ARGS="$COMMON_ARGS $@"
fi

echo "共享参数: $COMMON_ARGS"
echo ""

# ============================================================================
# 实验 (a): 无采样和长尾损失
# ============================================================================
echo "========================================================================"
echo "[1/3] 开始运行实验 (a): 无采样和长尾损失"
echo "========================================================================"
./run_ablation_experiments.sh a $COMMON_ARGS

echo ""
echo "实验 (a) 完成！"
echo ""
sleep 2

# ============================================================================
# 实验 (b): 仅无长尾损失
# ============================================================================
echo "========================================================================"
echo "[2/3] 开始运行实验 (b): 仅无长尾损失"
echo "========================================================================"
./run_ablation_experiments.sh b $COMMON_ARGS

echo ""
echo "实验 (b) 完成！"
echo ""
sleep 2

# ============================================================================
# 实验 (c): 仅无采样
# ============================================================================
echo "========================================================================"
echo "[3/3] 开始运行实验 (c): 仅无采样"
echo "========================================================================"
./run_ablation_experiments.sh c $COMMON_ARGS

echo ""
echo "实验 (c) 完成！"
echo ""

# ============================================================================
# 完成
# ============================================================================
echo "========================================================================"
echo "所有消融实验已完成！"
echo "========================================================================"
echo ""
echo "结果目录:"
echo "  - 实验 (a): output/ablation_a_no_sampling_no_loss_*/"
echo "  - 实验 (b): output/ablation_b_no_loss_only_*/"
echo "  - 实验 (c): output/ablation_c_no_sampling_only_*/"
echo ""
echo "请查看各目录中的 train_log.txt 和模型文件。"
echo "========================================================================"
